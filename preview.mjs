import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
const errs = [];
const c = await b.newContext({ viewport:{width:1440,height:1000} });
const p = await c.newPage();
p.on('pageerror', e => errs.push(e.message.slice(0,120)));
p.on('console', m => { if (m.type()==='error') errs.push('C:'+m.text().slice(0,120)); });
await p.goto('http://127.0.0.1:4173/pages/build-your-system', { waitUntil:'networkidle' });
await p.waitForTimeout(900);
await p.screenshot({ path:'/Users/lee/PHP_WORK/bags/.ref/pv-build.png' });
await p.goto('http://127.0.0.1:4173/pages/faq', { waitUntil:'networkidle' });
await p.waitForTimeout(600);
await p.screenshot({ path:'/Users/lee/PHP_WORK/bags/.ref/pv-faq.png', fullPage:true });
await p.goto('http://127.0.0.1:4173/collections/sale', { waitUntil:'networkidle' });
await p.waitForTimeout(800);
console.log('sale cards:', await p.locator('.pcard').count(), 'title:', await p.textContent('.collection-hero h1'));
await p.screenshot({ path:'/Users/lee/PHP_WORK/bags/.ref/pv-sale.png' });
const m = await (await b.newContext({ viewport:{width:390,height:844} })).newPage();
await m.goto('http://127.0.0.1:4173/collections/all', { waitUntil:'networkidle' });
await m.waitForTimeout(800);
await m.screenshot({ path:'/Users/lee/PHP_WORK/bags/.ref/pv-mobile-plp.png' });
console.log('errors:', [...new Set(errs)].slice(0,6));
await b.close();
